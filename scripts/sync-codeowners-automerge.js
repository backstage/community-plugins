// Keeps the lockfile-only CODEOWNERS entries in sync with the
// `autoMergeDependencies` flag in each workspace's bcp.json.
//
// For every opted-in workspace we add a line for its yarn.lock with the
// workspace's own owners plus the service account. That lets the service
// account approve PRs that only change that lockfile, while any other file
// in the workspace still needs a review from its owners.
//
// Usage:
//   node scripts/sync-codeowners-automerge.js          # update CODEOWNERS
//   node scripts/sync-codeowners-automerge.js --check  # exit 1 if out of date

import fs from 'node:fs/promises';
import { resolve } from 'node:path';
import * as url from 'node:url';
import { listWorkspaces } from './list-workspaces.js';

export const SERVICE_ACCOUNT = '@backstage-service';
export const BLOCK_START =
  '# BEGIN dependency automerge, generated by scripts/sync-codeowners-automerge.js from the "autoMergeDependencies" flag in bcp.json. Do not edit by hand.';
export const BLOCK_END = '# END dependency automerge';
const BLOCK_NOTE = [
  '#',
  '# These lines let @backstage-service approve PRs that only change these',
  '# lockfiles. They must stay at the end of this file: the last matching',
  '# pattern takes precedence, so anything below them that also matched',
  "# a workspace's yarn.lock would override them.",
].join('\n');

/**
 * Returns the owners listed for `/workspaces/<name>` in CODEOWNERS.
 */
export function getWorkspaceOwners(codeowners, workspace) {
  for (const line of codeowners.split('\n')) {
    const [pattern, ...owners] = line.trim().split(/\s+/);
    if (pattern === `/workspaces/${workspace}`) {
      return owners;
    }
  }
  return undefined;
}

/**
 * Returns CODEOWNERS content with the generated block replaced (or appended)
 * for the given opted-in workspaces.
 */
export function renderCodeowners(codeowners, workspaces) {
  const withoutBlock = removeBlock(codeowners).trimEnd();
  if (!workspaces.length) {
    return `${withoutBlock}\n`;
  }

  const lines = workspaces.map(workspace => {
    const owners = getWorkspaceOwners(withoutBlock, workspace);
    if (!owners) {
      throw new Error(
        `Workspace ${workspace} has autoMergeDependencies enabled but no /workspaces/${workspace} entry in CODEOWNERS`,
      );
    }
    const pattern = `/workspaces/${workspace}/yarn.lock`;
    return `${pattern.padEnd(72)}${[
      ...owners.filter(o => o !== SERVICE_ACCOUNT),
      SERVICE_ACCOUNT,
    ].join(' ')}`;
  });

  return `${withoutBlock}\n\n${BLOCK_START}\n${BLOCK_NOTE}\n${lines.join(
    '\n',
  )}\n${BLOCK_END}\n`;
}

function removeBlock(codeowners) {
  const start = codeowners.indexOf(BLOCK_START);
  if (start === -1) {
    return codeowners;
  }
  const end = codeowners.indexOf(BLOCK_END, start);
  if (end === -1) {
    throw new Error(`Found "${BLOCK_START}" without a matching end marker`);
  }
  return codeowners.slice(0, start) + codeowners.slice(end + BLOCK_END.length);
}

async function getOptedInWorkspaces(rootPath) {
  const optedIn = [];
  for (const workspace of await listWorkspaces()) {
    const name = workspace.replace(/\/$/, '');
    try {
      const bcp = JSON.parse(
        await fs.readFile(
          resolve(rootPath, 'workspaces', name, 'bcp.json'),
          'utf8',
        ),
      );
      if (bcp.autoMergeDependencies === true) {
        optedIn.push(name);
      }
    } catch (error) {
      if (error.code !== 'ENOENT') {
        throw error;
      }
    }
  }
  return optedIn.sort();
}

async function main(args) {
  const rootPath = resolve(
    url.fileURLToPath(new URL('.', import.meta.url)),
    '..',
  );
  const codeownersPath = resolve(rootPath, '.github', 'CODEOWNERS');
  const current = await fs.readFile(codeownersPath, 'utf8');
  const expected = renderCodeowners(
    current,
    await getOptedInWorkspaces(rootPath),
  );

  if (current === expected) {
    console.log('CODEOWNERS dependency automerge entries are up to date');
    return;
  }
  if (args.includes('--check')) {
    console.error(
      'CODEOWNERS dependency automerge entries are out of date. Run `node scripts/sync-codeowners-automerge.js` and commit the result.',
    );
    process.exit(1);
  }
  await fs.writeFile(codeownersPath, expected);
  console.log('Updated CODEOWNERS dependency automerge entries');
}

if (import.meta.url === url.pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch(error => {
    console.error(error.stack || error);
    process.exit(1);
  });
}
